"""Stage `handoff`: freeze the modeling result for the rigging skill.

  python run_stage.py run export_handoff --manifest P -- [--allow-warnings] [--allow-errors]

Checks: mesh_audit done and not stale; every rigid component has a bone_hint
that is a joint; membranes have influences; export groups under the Roblox
per-mesh triangle limit. Then saves a checkpoint .blend (handoff_NNN), refreshes
landmarks from LM_* empties, and writes manifest.handoff plus
reports/geometry_materials_report.md (short human-readable report).

The handoff checkpoint must be approved by the user before rigging:
  manifest_tool.py approve --manifest P --checkpoint handoff_NNN

STATUS: implemented, untested.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pipeline_common as pc  # noqa: E402

STAGE = "handoff"


def write_report(mpath, data, problems) -> Path:
    comps = data.get("components", [])
    roles: dict[str, list[int]] = {}
    for c in comps:
        roles.setdefault(c["role"], []).append(int(c.get("tris", 0)))
    lines = [f"# Geometry and materials report - {data['creature_id']}", "",
             f"Generated {pc.now_iso()} by export_handoff.py. Status: generated by untested pipeline scripts;",
             "verify visually before relying on it.", "",
             "## Components by role", "", "| role | count | tris |", "|---|---:|---:|"]
    for r, t in sorted(roles.items()):
        lines.append(f"| {r} | {len(t)} | {sum(t)} |")
    lines += ["", "## Export groups (one Roblox MeshPart each)", "", "| group | components | tris | limit |",
              "|---|---:|---:|---:|"]
    for g in data.get("export_groups", []):
        lines.append(f"| {g['name']} | {len(g['components'])} | {g.get('tris', '?')} | {g.get('max_tris', '?')} |")
    lines += ["", "## Textures", "", "| group | map | px | space | origin |", "|---|---|---:|---|---|"]
    for t in data.get("textures", []):
        flag = " (approximation)" if t.get("approximation") else ""
        lines.append(f"| {t['material_group']} | {t['map']} | {t.get('resolution')} | {t['color_space']} | "
                     f"{t.get('origin')}{flag} |")
    sil = data["stages"].get("silhouette_compare", {}).get("history", [])
    lines += ["", "## Silhouette agreement (outline only)", ""]
    lines += [f"- iteration {h['iteration']}: mean IoU {h['mean_iou']}" for h in sil[-5:]] or ["- not measured"]
    lines += ["", "## Open defects", ""]
    od = pc.open_defects(data, "warning")
    lines += [f"- {d['id']} [{d['severity']}] {d['stage']}: {d['description']}" for d in od[:30]] or ["- none"]
    if problems:
        lines += ["", "## Handoff blockers", ""] + [f"- {p}" for p in problems]
    path = pc.project_root(mpath) / "reports" / "geometry_materials_report.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def run(params: dict) -> dict:
    import bpy
    pc.require_blender()
    mpath, data = pc.load_manifest(params["manifest"])
    pc.ensure_working_blend(mpath, data, adopt_current=bool(params.get("adopt_current")))
    pc.ensure_object_mode()
    problems, warnings = [], []
    st = data["stages"]
    if st.get("mesh_audit", {}).get("status") not in ("done", "approved"):
        problems.append(f"mesh_audit is {st.get('mesh_audit', {}).get('status')} (run mesh_audit.py)")
    if st.get("uv_pbr", {}).get("status") not in ("done", "approved"):
        warnings.append("uv_pbr not done: no textures in handoff")
    joints = {j["name"] for j in data.get("joints", [])}
    for c in data.get("components", []):
        if bpy.data.objects.get(c["name"]) is None:
            problems.append(f"component object missing: {c['name']}")
        elif c["role"] == "membrane":
            if not c.get("influences"):
                problems.append(f"membrane {c['name']} has no influences")
            elif set(c["influences"]) - joints:
                problems.append(f"membrane {c['name']} influences unknown joints {sorted(set(c['influences']) - joints)[:5]}")
        elif c.get("bone_hint") not in joints:
            problems.append(f"{c['name']}: bone_hint {c.get('bone_hint')!r} is not a joint")
    mat_of = {c["name"]: c.get("material_group") for c in data.get("components", [])}
    for g in data.get("export_groups", []):
        if g.get("tris", 0) > g.get("max_tris", 20000):
            problems.append(f"export group {g['name']} over triangle limit")
        mats = sorted({mat_of.get(n) for n in g["components"]} - {None})
        g["material_groups"] = mats
        if len(mats) > 1:  # one MeshPart carries one SurfaceAppearance
            problems.append(f"export group {g['name']} mixes material groups {mats}; "
                            "use one material group per export group")
    errs = pc.open_defects(data, "error")
    if errs and not params.get("allow_errors"):
        problems.append(f"{len(errs)} open error defects (use --allow-errors to override knowingly)")
    warns = [d for d in pc.open_defects(data, "warning") if d["severity"] == "warning"]
    if warns and not params.get("allow_warnings"):
        warnings.append(f"{len(warns)} open warnings")
    for obj in bpy.data.objects:
        if obj.type == "EMPTY" and obj.name.startswith("LM_"):
            name = obj.name[3:]
            entry = data.setdefault("landmarks", {}).setdefault(name, {"source": "scene_edit"})
            entry["co"] = [round(x, 5) for x in obj.matrix_world.translation]
            entry.setdefault("complete", True)
    report = write_report(mpath, data, problems)
    if problems:
        data["handoff"] = {"ready": False, "blockers": problems[:30], "checked_at": pc.now_iso()}
        pc.set_stage(data, STAGE, "failed", {"blockers": len(problems)})
        pc.save_manifest(mpath, data)
        return {"ok": False, "stage": STAGE, "blockers": problems[:10], "report": pc.to_rel(mpath, report)}
    pc.save_working(mpath, data, params.get("save"))
    ck = pc.save_checkpoint(mpath, data, STAGE, "modeling handoff")
    data["handoff"] = {
        "ready": True, "created_at": pc.now_iso(), "checkpoint": ck["id"], "blend": ck["path"],
        "working_blend": data["paths"]["working_blend"], "schema_version": pc.SCHEMA_VERSION,
        "components": len(data.get("components", [])), "joints": len(joints),
        "export_groups": [g["name"] for g in data.get("export_groups", [])],
        "textures": len(data.get("textures", [])), "warnings": warnings,
        "requires_user_approval": True,
    }
    pc.set_stage(data, STAGE, "done", {"checkpoint": ck["id"], "warnings": len(warnings)})
    pc.save_manifest(mpath, data)
    return {"stage": STAGE, "ready": True, "checkpoint": ck["id"], "warnings": warnings,
            "report": pc.to_rel(mpath, report),
            "next": f"Review, then: manifest_tool.py approve --manifest <P> --checkpoint {ck['id']}"}


def main() -> None:
    p = pc.base_parser(__doc__)
    p.add_argument("--allow-warnings", action="store_true")
    p.add_argument("--allow-errors", action="store_true")
    pc.cli_entry(run, p)


if __name__ == "__main__":
    main()
